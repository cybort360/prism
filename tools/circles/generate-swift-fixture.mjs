#!/usr/bin/env node
// Renders proof/circles/safe-tx-vectors.json into a Swift source file.
//
// The vectors are embedded as literals rather than loaded as a bundle resource so the exact same
// file runs under `swift test` on Linux and inside the iOS test target, with no resource plumbing
// and no chance of the two reading different data.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../proof/circles/safe-tx-vectors.json');
const out = resolve(here, '../../ios/PrismTests/CircleSafeTxVectorsFixture.swift');
const file = JSON.parse(readFileSync(src, 'utf8'));
const q = (s) => JSON.stringify(String(s));

const rows = file.vectors.map((v) => `    CircleSafeTxVector(
      name: ${q(v.name)},
      safeAddress: ${q(v.safeAddress)},
      chainId: ${q(v.chainId)},
      to: ${q(v.to)},
      value: ${q(v.value)},
      data: ${q(v.data)},
      operation: ${v.operation},
      safeTxGas: ${q(v.safeTxGas)},
      baseGas: ${q(v.baseGas)},
      gasPrice: ${q(v.gasPrice)},
      gasToken: ${q(v.gasToken)},
      refundReceiver: ${q(v.refundReceiver)},
      nonce: ${q(v.nonce)},
      humanRecipient: ${q(v.humanRecipient)},
      amountDisplay: ${q(v.amountDisplay)},
      domainSeparator: ${q(v.domainSeparator)},
      preimage: ${q(v.preimage)},
      safeTxHash: ${q(v.safeTxHash)}
    )`).join(',\n');

writeFileSync(out, `// Generated by tools/circles/generate-swift-fixture.mjs — do not edit by hand.
//
// Source of truth: proof/circles/safe-tx-vectors.json, produced by asking a real Safe v1.4.1 on
// Monad testnet for getTransactionHash(), and independently confirmed by the official Safe
// protocol-kit (tools/circles/verify-vectors.mjs).
//
// Safe version: ${file.safeVersion}
// Regenerate:   cd tools/circles && npm run fixture

struct CircleSafeTxVector {
  let name: String
  let safeAddress: String
  let chainId: String
  let to: String
  let value: String
  let data: String
  let operation: UInt8
  let safeTxGas: String
  let baseGas: String
  let gasPrice: String
  let gasToken: String
  let refundReceiver: String
  let nonce: String
  let humanRecipient: String
  let amountDisplay: String
  let domainSeparator: String
  let preimage: String
  let safeTxHash: String
}

enum CircleSafeTxVectors {
  static let safeVersion = ${q(file.safeVersion)}
  static let all: [CircleSafeTxVector] = [
${rows}
  ]
}
`);
console.log(`wrote ${out} (${file.vectors.length} vectors, Safe ${file.safeVersion})`);
